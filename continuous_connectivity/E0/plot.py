#!/usr/bin/env python3
"""Plot E0 logs (also reusable for subsequent experiments with same CSV schema)."""
import argparse,csv,json
from pathlib import Path
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

def rows(p):
    if not p.exists():return []
    with p.open(newline='') as f:return list(csv.DictReader(f))
def floats(rs,k):return [float(r[k]) for r in rs if r.get(k) not in ('',None)]
def main():
    p=argparse.ArgumentParser();p.add_argument('run_dir');a=p.parse_args()
    base=Path(a.run_dir);out=base/'plots';out.mkdir(exist_ok=True)
    steps=rows(base/'steps.csv');vals=rows(base/'validation.csv')
    if not steps:raise SystemExit('No step measurements found')
    def save(fname,x,y,xlabel,ylabel,title,**kw):
        fig,ax=plt.subplots(figsize=(8.5,4.2));ax.plot(x,y,**kw);ax.set(xlabel=xlabel,ylabel=ylabel,title=title)
        ax.grid(alpha=.25);fig.tight_layout();fig.savefig(out/fname,dpi=180);plt.close(fig)
    sec=floats(steps,'elapsed_s');step_ids=floats(steps,'step')
    save('01_train_loss.png',sec,floats(steps,'loss'),'Wall-clock elapsed (s)','Cross-entropy loss','E0 — Training loss',alpha=.65,lw=1)
    if vals:
        x=floats(vals,'elapsed_s')
        save('02_validation_accuracy.png',x,[100*v for v in floats(vals,'val_accuracy')],
             'Wall-clock elapsed (s)','Accuracy (%)','E0 — Validation accuracy',marker='o',lw=1.7)
        save('03_validation_loss.png',x,floats(vals,'val_loss'),
             'Wall-clock elapsed (s)','Cross-entropy loss','E0 — Validation loss',marker='o',lw=1.7)
    save('04_step_duration.png',sec,[1000*v for v in floats(steps,'step_s')],
         'Wall-clock elapsed (s)','Step duration (ms)','E0 — Per-step time',alpha=.7,lw=.9)
    x=floats(steps,'elapsed_s');seen=floats(steps,'samples_seen')
    save('05_samples_processed.png',x,seen,'Wall-clock elapsed (s)','Samples processed',
         'E0 — Training progress',lw=1.8)
    # GPU CSV generated by nvidia-smi, sampled in wall-clock time; timestamps aren't on training monotonic clock.
    gpu=rows(base/'gpu.csv')
    if gpu:
        # nvidia-smi file has no header; parse fields directly with csv.reader; use index as sample number.
        pass
    gpupath=base/'gpu.csv'
    if gpupath.exists():
        with gpupath.open(newline='') as f: samples=list(csv.reader(f))
        u=[]
        for r in samples:
            if len(r)>=3:
                try:u.append(float(r[2].strip()))
                except ValueError:pass
        if u:save('06_gpu_utilization.png',list(range(len(u))),u,
                  'GPU sample number (sampling interval set in manifest)','GPU utilization (%)',
                  'E0 — GPU utilization (nvidia-smi)',lw=1)
    print('Saved plots in',out)
if __name__=='__main__':main()
